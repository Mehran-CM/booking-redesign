// Generates src/styles/tokens.css from src/tokens/tokens.json (single source of truth).
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../src/tokens/tokens.json', import.meta.url), 'utf8'));
const lines = [];
const resolve = (v) =>
  typeof v === 'string' && v.startsWith('{')
    ? `var(--${v.slice(1, -1).replace(/\./g, '-')})`
    : v;
const unit = (n) => (typeof n === 'number' ? `${n}px` : n);

const walk = (obj, path, fmt = (v) => v) => {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$')) continue;
    const p = [...path, k];
    if (v && typeof v === 'object') walk(v, p, fmt);
    else lines.push(`  --${p.join('-')}: ${fmt(resolve(v))};`);
  }
};

walk(tokens.color, ['color']);
lines.push(`  --font-family: ${tokens.font.family};`);
for (const [name, s] of Object.entries(tokens.font['text-styles'])) {
  lines.push(`  --font-${name}-size: ${unit(s.size)};`);
  lines.push(`  --font-${name}-line: ${unit(s.lineHeight)};`);
  lines.push(`  --font-${name}-weight: ${s.weight};`);
}
walk(tokens.space, ['space'], (v) => unit(Number(v)));
walk(tokens.radius, ['radius'], (v) => unit(Number(v)));
walk(tokens.shadow, ['shadow']);
walk(tokens.size, ['size'], (v) => unit(Number(v)));
for (const [name, m] of Object.entries(tokens.motion)) {
  lines.push(`  --motion-${name}: ${m.duration}ms ${m.easing};`);
  lines.push(`  --motion-${name}-duration: ${m.duration}ms;`);
}

const css = `/* GENERATED by scripts/gen-tokens.mjs from src/tokens/tokens.json — do not edit. */\n:root {\n${lines.join('\n')}\n}\n\n@media (prefers-reduced-motion: reduce) {\n  :root {\n    --motion-enter-m-duration: 0ms;\n    --motion-move-m-duration: 0ms;\n    --motion-feedback-s-duration: 0ms;\n    --motion-enter-m: 0ms linear;\n    --motion-move-m: 0ms linear;\n    --motion-feedback-s: 0ms linear;\n  }\n}\n`;
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);
console.log(`tokens.css: ${lines.length} variables`);
